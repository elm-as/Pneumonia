"""Saliency overlay generation blending radiographs with Grad-CAM heatmaps."""

from typing import Tuple
import cv2
import numpy as np
from PIL import Image


def overlay_cam_on_image(
    image: Image.Image,
    cam_heatmap: np.ndarray,
    alpha: float = 0.5,
) -> np.ndarray:
    """Superimpose 2D Grad-CAM heatmap over original radiograph.

    Args:
        image: Original PIL radiograph (Grayscale or RGB).
        cam_heatmap: 2D numpy array in [0, 1] generated by GradCAM.
        alpha: Blending weight for the colorized activation overlay.

    Returns:
        RGB numpy array with overlaid activation heatmap.
    """
    rgb_img = np.array(image.convert("RGB"), dtype=np.float32) / 255.0
    h, w = rgb_img.shape[:2]

    # Resize CAM to match original image dimensions
    resized_cam = cv2.resize(cam_heatmap, (w, h), interpolation=cv2.INTER_LINEAR)
    heatmap_uint8 = np.uint8(255 * resized_cam)

    # Apply JET colormap (blue: low activation, red: high clinical focus)
    color_map = cv2.applyColorMap(heatmap_uint8, cv2.COLORMAP_JET)
    color_map_rgb = cv2.cvtColor(color_map, cv2.COLOR_BGR2RGB).astype(np.float32) / 255.0

    # Alpha blending
    blended = alpha * color_map_rgb + (1.0 - alpha) * rgb_img
    blended = np.clip(blended, 0.0, 1.0)

    return np.uint8(255 * blended)

